def extract_bits(stream_value: int, bit_offset: int, bit_size: int, total_bits: int) -> int:
	shift = total_bits - bit_offset - bit_size
	mask = (1 << bit_size) - 1
	return (stream_value >> shift) & mask



def insert_bits(stream_value: int, bit_offset: int, bit_size: int, raw_value: int, total_bits: int) -> int:
	shift = total_bits - bit_offset - bit_size
	mask = ((1 << bit_size) - 1) << shift
	stream_value &= ~mask
	stream_value |= (raw_value << shift) & mask
	return stream_value



def decode_field_value(field: FieldRule, raw_value: int):
	if field.kind == "uint":
		return raw_value
	if field.kind == "pointer32":
		return raw_value
	if field.kind == "float16":
		return struct.unpack(">e", raw_value.to_bytes(2, "big"))[0]
	if field.kind == "float32":
		return struct.unpack(">f", raw_value.to_bytes(4, "big"))[0]
	return raw_value



def encode_field_value(field: FieldRule, value) -> int:
	if field.kind == "uint":
		integer_value = parse_int_maybe_hex(value)
		max_value = (1 << field.bit_size) - 1
		if not 0 <= integer_value <= max_value:
			raise ValidationError(f"{field.display_name} must be between 0 and {max_value}")
		return integer_value
	if field.kind == "pointer32":
		integer_value = parse_int_maybe_hex(value)
		if not 0 <= integer_value <= 0xFFFFFFFF:
			raise ValidationError(f"{field.display_name} must be between 0 and 0xFFFFFFFF")
		return integer_value
	if field.kind == "float16":
		float_value = parse_float(value, field.display_name)
		return int.from_bytes(struct.pack(">e", float_value), "big")
	if field.kind == "float32":
		float_value = parse_float(value, field.display_name)
		return int.from_bytes(struct.pack(">f", float_value), "big")
	return parse_int_maybe_hex(value)



def parse_int_maybe_hex(value) -> int:
	if isinstance(value, bool):
		return int(value)
	if isinstance(value, int):
		return value
	text = str(value).strip()
	if not text:
		raise ValidationError("Value cannot be empty")
	if text.lower().startswith("0x"):
		return int(text, 16)
	return int(text, 10)



def parse_float(value, field_name: str) -> float:
	text = str(value).strip()
	if not text:
		raise ValidationError(f"{field_name} cannot be empty")
	try:
		return float(text)
	except ValueError as exc:
		raise ValidationError(f"{field_name} must be a valid number") from exc



def format_float(value: float) -> str:
	if not math.isfinite(value):
		return str(value)
	text = f"{float(value):.15g}"
	if text == "-0":
		return "0"
	return text



def read_ascii_cstring_with_capacity(blob: bytes, offset: int) -> Tuple[str, int]:
	if offset < 0 or offset >= len(blob):
		raise ValidationError(f"Offset 0x{offset:06X} is outside the file")
	end = offset
	while end < len(blob) and blob[end] != 0:
		end += 1
	if end >= len(blob):
		raise ValidationError("Reached end of file before finding a null terminator")
	raw = blob[offset:end]
	try:
		text = raw.decode("ascii")
	except UnicodeDecodeError:
		text = raw.decode("latin-1")
	return text, len(raw)



def write_fixed_ascii_cstring(blob: bytearray, offset: int, text: str, max_chars: int):
	ascii_text = normalize_newlines(text)
	try:
		raw = ascii_text.encode("ascii")
	except UnicodeEncodeError as exc:
		raise ValidationError("Archive strings must be ASCII") from exc
	if len(raw) > max_chars:
		raise ValidationError(
			f"Archive string {ascii_text!r} is too long. Max allowed length here is {max_chars} characters."
		)
	end = offset + max_chars + 1
	if end > len(blob):
		raise ValidationError(f"String write at 0x{offset:06X} would run past the end of the file")
	padding = b"\x00" * (max_chars - len(raw) + 1)
	blob[offset:end] = raw + padding


