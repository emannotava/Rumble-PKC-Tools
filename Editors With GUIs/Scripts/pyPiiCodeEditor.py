def load_logic_config_from_text(text: str) -> LogicConfig:
	lines = [line.strip() for line in text.splitlines() if line.strip()]
	if len(lines) < 2:
		raise ConfigError("Embedded logic data must contain at least two non-empty lines")
	name_parts = [part.strip() for part in lines[0].split(";") if part.strip()]
	bit_parts = [part.strip() for part in lines[1].split(";") if part.strip()]
	if len(name_parts) != len(bit_parts):
		raise ConfigError("Embedded logic field-name count does not match bit-size count")

	fields: List[FieldRule] = []
	bit_offset = 0
	for raw_name, bit_text in zip(name_parts, bit_parts):
		bit_size = parse_bit_size(bit_text)
		kind = infer_field_kind(raw_name)
		display_name = prettify_field_name(raw_name)
		fields.append(FieldRule(raw_name=raw_name, display_name=display_name, bit_size=bit_size, bit_offset=bit_offset, kind=kind))
		bit_offset += bit_size
	if bit_offset != RECORD_BITS:
		raise ConfigError(f"Embedded logic totals {bit_offset} bits instead of {RECORD_BITS}")
	return LogicConfig(fields)


def load_offsets_config_from_text(text: str) -> List[OffsetRule]:
	lines = [line.rstrip("\r\n") for line in text.splitlines() if line.strip()]
	if not lines:
		raise ConfigError("Embedded offsets data is empty")
	headers = [part.strip() for part in lines[0].split(";")]
	expected_headers = [
		"Offset",
		"Male_Archive_String_Name_Pointer",
		"Male_Archive_String_Name_Substitute",
		"Female_Archive_String_Name_Pointer",
		"Female_Archive_String_Name_Substitute",
		"NAME",
	]
	if headers[:6] != expected_headers:
		raise ConfigError("Embedded offsets header row does not match the expected format")

	offsets: List[OffsetRule] = []
	for line_number, line in enumerate(lines[1:], start=2):
		parts = [part.strip() for part in line.split(";")]
		if len(parts) < 6:
			raise ConfigError(f"Embedded offsets line {line_number} has fewer than 6 columns")
		offsets.append(
			OffsetRule(
				offset=parse_hex_int(parts[0]),
				male_pointer=parse_hex_int(parts[1]),
				male_substitute=parse_hex_int(parts[2]),
				female_pointer=parse_hex_int(parts[3]),
				female_substitute=parse_hex_int(parts[4]),
				name=parts[5],
			)
		)
	if not offsets:
		raise ConfigError("Embedded offsets data did not contain any data rows")
	return offsets


def parse_bit_size(text: str) -> int:
	lowered = text.strip().lower()
	if not lowered.endswith("bits"):
		raise ConfigError(f"Invalid bit-size text: {text!r}")
	value_text = lowered[:-4].strip()
	return int(value_text)



def infer_field_kind(raw_name: str) -> str:
	if "StringPointer" in raw_name or raw_name.endswith("Pointer"):
		return "pointer32"
	if raw_name.startswith("Int_"):
		return "uint"
	if raw_name.startswith("f16_"):
		return "float16"
	if raw_name.startswith("f32_"):
		return "float32"
	return "uint"



def prettify_field_name(raw_name: str) -> str:
	text = raw_name
	for prefix in ("Int_", "f16_", "f32_"):
		if text.startswith(prefix):
			text = text[len(prefix):]
			break
	text = text.replace("__deprecated__", "Deprecated ")
	text = text.replace("_", " ")
	text = text.replace("NDex", "National Dex")
	text = text.replace("ID", " ID")
	text = text.replace("Anm", "Animation")
	text = text.replace("Unk", "Unknown")
	text = text.replace("Coeff", "Coefficient")
	text = text.replace("CoEff", "Coefficient")
	text = text.replace("ArchiveName", "Archive Name")
	text = text.replace("WalkSpeed", "Walk Speed")
	text = text.replace("WalkAnm", "Walk Animation")
	text = text.replace("FlyHeight", "Fly Height")
	text = " ".join(text.split())
	return text.strip()


